<h3>Testando o Do While</h3>
<?php

    $j = 0;

    do {
        echo "Testando do while: $j <br>";

        $j++;
    } while($j < 10);
?>

<hr>

<h3>Decremento com Do While</h3>

<?php

    $i = 10;

    do {
        echo "Testando do while 2: $i <br>";
        $i--; // decremento
    } while($i > 0);

?>